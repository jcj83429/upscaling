def stripLinearLightFlags(flags):
    cleanedFlags = []
    i = 0
    while i < len(flags):
        if flags[i] == '-colorspace':
            i += 2 # skip next
        else:
            cleanedFlags += [flags[i]]
            i+= 1
    return cleanedFlags

